#!/usr/bin/env python3
"""Turn RDADA verified candidate files into TypeScript Source records (src/data/extra/g.ts) and an id map.
One Source per work (URL); every verified passage for that work is kept in `evidence`. Sources whose limits carry the
'unauthorised-looking upload' note are cited by publication only: the URL is omitted. All reliability is the editor's reading
of the source type; nothing here is a RDADA judgement."""
import json, glob, re, sys, hashlib
from pathlib import Path
ROOT = Path(sys.argv[1] if len(sys.argv) > 1 else 'rdada_runs')
files = sorted(glob.glob(str(ROOT / '*' / 'notes' / '*.verified.json')))
def slug(s): return re.sub(r'[^a-z0-9]+', '', s.lower())
def esc(s): return str(s).replace('\\', '\\\\').replace("'", "\\'").replace('\n', ' ')
works = {}
for f in files:
    for i, c in enumerate(json.load(open(f))):
        works.setdefault(c['url'].rstrip('/'), []).append((Path(f).parent.parent.name + '/' + Path(f).name.split('.')[0], i, c))
used, out, idmap, passages, pc = set(), [], {}, [], {}
for url, items in works.items():
    c0 = items[0][2]
    wiki = 'wikipedia.org' in url
    au = (c0.get('authors') or '').split(';')[0].split(',')[0].strip()
    if wiki: base = 'w_' + slug(url.split('?')[0].rsplit('/', 1)[-1])[:28]
    else: base = 'g_' + (slug(au.split(' ')[0]) or slug(' '.join(c0['title'].split()[:2]))[:14]) + str(c0.get('year') or 'nd')
    sid = base; n = 2
    while sid in used: sid = f'{base}{chr(96 + n)}'; n += 1
    used.add(sid)
    for b, i, c in items:
        idmap[f'{b}#{i}'] = sid
        tx = c.get('text')
        if tx:
            key = 'p_' + slug(tx['work'])[:14] + '_' + slug(tx['locator'])[:12]
            pc[key] = pc.get(key, 0) + 1; pid = key if pc[key] == 1 else f'{key}{pc[key]}'
            idmap[f'{b}#{i}#passage'] = pid
            comp = tx.get('composition') or {}
            passages.append("  { id: '%s', work: '%s', locator: '%s', language: '%s', quote: '%s', edition: '%s', compStart: %s, compEnd: %s, compBasis: '%s', witness: '%s', src: '%s' }," % (pid, esc(tx['work']), esc(tx['locator']), esc(tx['language']), esc(c['quote']), esc(tx['edition']), comp.get('start') if comp.get('start') is not None else 'null', comp.get('end') if comp.get('end') is not None else 'null', esc(comp.get('basis', '')), esc(tx['witness']), sid))
    unauth = any('unauthorised-looking upload' in (c.get('limits') or '') for _, _, c in items)
    kinds = {c['kind'] for _, _, c in items}; kind = 'skeptical' if kinds == {'skeptical'} else next(iter(sorted(kinds - {'skeptical'}))) if kinds - {'skeptical'} else 'secondary'
    kind = {'official': 'secondary'}.get(kind, kind)
    rel = 'low' if wiki else ('medium' if kind in ('secondary', 'alternative') or any(x in url for x in ('archive.org',)) else 'high')
    if kind == 'primary' and any(x in url for x in ('whiterose', 'ora.ox', 'cambridge.org', 'ncbi')): rel = 'high'
    year = c0.get('year'); venue = c0.get('venue') or ''
    who = c0.get('authors') or ('Wikipedia contributors' if wiki else '')
    cite = f"{who + ' ' if who else ''}({year if year else 'n.d.'}) {c0['title']}." + (f" {venue}." if venue and not wiki else '') + (f" doi:{c0['doi']}." if c0.get('doi') else '') + ('' if unauth else f" {url.split('?')[0] if wiki else url}") + f" (accessed {c0['accessed']}; opened by the RDADA agent and its quotes checked by a separate verifier)."
    ev = ' | '.join(dict.fromkeys(c['quote'] for _, _, c in items))
    lim = ' '.join(dict.fromkeys(re.sub(r'\s*copy: unauthorised-looking upload; cite the publication, not this URL\.?', '', (c.get('limits') or '')).strip() for _, _, c in items if c.get('limits')))
    if unauth: lim += ' The copy read was a user-uploaded scan; this entry cites the publication, not the upload.'
    disc = c0.get('discipline') or 'History'
    out.append(f"  S('{sid}', '{esc(cite)}', '{kind}', '{esc(disc)}', '{rel}', 'Passages quoted by the RDADA researcher and re-found verbatim by a separate verifier.', '{esc(ev)}', 'None stated.', '{esc(lim.strip())}'),")
hdr = """import type { Passage, Source } from '../../types';
// Generated by scripts/candidates-to-sources.py from rdada_runs/*/notes/*.verified.json. Do not edit by hand; edit the generator or the run.
type K = Source['kind']; type R = Source['reliability'];
const S = (id: string, cite: string, kind: K, discipline: string, reliability: R, methodology: string, evidence: string, conflicts: string, note?: string): Source =>
  ({ id, cite, kind, discipline, reliability, methodology, evidence, conflicts, note });
export const SOURCES_G: Source[] = [
"""
Path('src/data/extra/g.ts').write_text(hdr + '\n'.join(out) + '\n];\n\nexport const PASSAGES: Passage[] = [\n' + '\n'.join(passages) + '\n];\n')
json.dump(idmap, open(ROOT / 'idmap.json', 'w'), indent=1)
print(len(works), 'sources from', sum(len(v) for v in works.values()), 'passages')
